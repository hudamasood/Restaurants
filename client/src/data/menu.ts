export function dishBySlug(slug: string) {
  return DISHES.find((d) => d.slug === slug);
}

export function dishById(id: string) {
  return DISHES.find((d) => d.id === id);
}

/** Adjacent signature dishes, for prev/next chaining on /menu/:slug. */
export function adjacentSignatures(slug: string) {
  const i = SIGNATURE_DISHES.findIndex((d) => d.slug === slug);
  if (i === -1) return { prev: undefined, next: undefined, index: 0, total: SIGNATURE_DISHES.length };
  return {
    prev: SIGNATURE_DISHES[(i - 1 + SIGNATURE_DISHES.length) % SIGNATURE_DISHES.length],
    next: SIGNATURE_DISHES[(i + 1) % SIGNATURE_DISHES.length],
    index: i + 1,
    total: SIGNATURE_DISHES.length,
  };
}
